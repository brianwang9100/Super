            category: .historical,
            title: "Historical context",
            content: .text("Written to a church Paul had not yet visited, made up of both Jewish and Gentile believers. Tensions between the two groups frame much of the letter."),
            provenance: "Generated by AFM 3.0 · Nov 27, 2026"
        ),
    ]

