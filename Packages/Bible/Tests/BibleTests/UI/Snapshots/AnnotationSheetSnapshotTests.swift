             body: "Paul of Tarsus, writing from Corinth around 57 AD — the longest and most systematic of his letters."),
        text(id: "sum", category: .summary, title: "Summary",
             body: "The golden chain of salvation: foreknown, predestined, called, justified, glorified."),
        text(id: "hist", category: .historical, title: "Historical context",
